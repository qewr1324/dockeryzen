const nav = document.getElementById("nav");
const crumb = document.getElementById("crumb");
const infoCard = document.getElementById("infoCard");
const infoTitle = document.getElementById("infoTitle");
const infoDesc = document.getElementById("infoDesc");
const infoList = document.getElementById("infoList");
const visual = document.getElementById("visual");
const visualIco = document.getElementById("visualIco");
const visualLabel = document.getElementById("visualLabel");
const stat1 = document.getElementById("stat1");
const stat2 = document.getElementById("stat2");
const stat3 = document.getElementById("stat3");
const code = document.getElementById("code");

function render(key) {
	const d = DATA[key];
	if (!d) return;

	// nav active
	nav.querySelectorAll("button").forEach((b) => {
		b.classList.toggle("active", b.dataset.key === key);
	});

	// crumb
	crumb.textContent = d.crumb;

	// info
	infoCard.classList.remove("fade");
	visual.classList.remove("fade");
	void infoCard.offsetWidth;

	infoTitle.textContent = d.title;
	infoDesc.textContent = d.desc;
	infoList.innerHTML = d.list.map((t) => `<div>${t}</div>`).join("");

	visualIco.textContent = d.ico;
	visualLabel.textContent = d.label;
	stat1.textContent = d.stats[0];
	stat2.textContent = d.stats[1];
	stat3.textContent = d.stats[2];

	code.innerHTML = d.code;

	infoCard.classList.add("fade");
	visual.classList.add("fade");
}

nav.addEventListener("click", (e) => {
	const btn = e.target.closest("button");
	if (!btn) return;
	render(btn.dataset.key);
});

// prevent any scroll on body
document.addEventListener(
	"wheel",
	(e) => {
		e.preventDefault();
	},
	{ passive: false },
);

// init
render("overview");
